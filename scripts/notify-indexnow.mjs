#!/usr/bin/env node
/**
 * IndexNow notifier — pushes the live sitemap URLs to IndexNow so
 * Bing (and via Bing: DuckDuckGo, Yahoo, Ecosia, Brave, ChatGPT Search)
 * re-crawl the site sooner after a deploy.
 *
 * IndexNow is a push protocol that supersedes manual URL submission
 * in webmaster tools. We push our 40+ URLs in one request; Bing reads
 * them within minutes, not days.
 *
 * Usage:
 *   npm run indexnow              # push every URL in sitemap.xml
 *   npm run indexnow -- url1 url2 # push only the named URLs
 *
 * The key file at /public/3459a91ea902e033e5245b0b3c401b6a.txt proves
 * ownership of the domain. Don't rename or delete it — IndexNow
 * verifies the key matches before accepting submissions.
 *
 * Bing's own IndexNow status page:
 *   https://www.bing.com/indexnow
 *
 * Endpoint docs:
 *   https://www.indexnow.org/documentation
 */

const KEY = "3459a91ea902e033e5245b0b3c401b6a";
// 2026-06-01 — flipped from www to apex to match SITE_URL change.
// IndexNow expects the canonical host, not the redirect-source.
const HOST = "bipe.ac.in";
const KEY_LOCATION = `https://${HOST}/${KEY}.txt`;
const SITEMAP_URL = `https://${HOST}/sitemap.xml`;
const INDEXNOW_ENDPOINT = "https://api.indexnow.org/indexnow";

async function loadUrlsFromSitemap() {
  const res = await fetch(SITEMAP_URL);
  if (!res.ok) {
    throw new Error(`Sitemap fetch failed: ${res.status} ${res.statusText}`);
  }
  const xml = await res.text();
  // Cheap-but-reliable: pull every <loc>...</loc> with a regex. The
  // sitemap is generated by Next; well-formed and predictable.
  const matches = xml.match(/<loc>([^<]+)<\/loc>/g) || [];
  return matches.map((m) => m.replace(/<\/?loc>/g, "").trim()).filter(Boolean);
}

async function notify(urlList) {
  if (!urlList.length) {
    console.error("No URLs to submit. Exiting.");
    process.exit(1);
  }

  const body = {
    host: HOST,
    key: KEY,
    keyLocation: KEY_LOCATION,
    urlList,
  };

  console.log(`→ POST ${INDEXNOW_ENDPOINT}`);
  console.log(`  host: ${HOST}`);
  console.log(`  keyLocation: ${KEY_LOCATION}`);
  console.log(`  urlList: ${urlList.length} URL${urlList.length === 1 ? "" : "s"}`);
  for (const u of urlList.slice(0, 5)) console.log(`    - ${u}`);
  if (urlList.length > 5) console.log(`    … (${urlList.length - 5} more)`);

  const res = await fetch(INDEXNOW_ENDPOINT, {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: JSON.stringify(body),
  });

  // IndexNow returns:
  //   200 — accepted (note: some keys say "OK" some say nothing in body)
  //   202 — accepted, processing
  //   400 — bad request (key format, malformed JSON, etc.)
  //   403 — key not found at keyLocation, or doesn't match host
  //   422 — URL is in a list that's not from the claimed host
  //   429 — rate limit (very rare for this volume)
  const text = await res.text();
  console.log(`← ${res.status} ${res.statusText}`);
  if (text) console.log(`  body: ${text.slice(0, 200)}`);

  if (res.status >= 200 && res.status < 300) {
    console.log(`✓ Submitted ${urlList.length} URL${urlList.length === 1 ? "" : "s"} to IndexNow.`);
    process.exit(0);
  } else {
    console.error(`✗ IndexNow rejected the submission.`);
    if (res.status === 403) {
      console.error(`  → Check ${KEY_LOCATION} returns exactly: ${KEY}`);
    }
    process.exit(2);
  }
}

async function main() {
  // Accept URLs as CLI args, or fall back to the full sitemap.
  // Strip the "--" that npm prepends when forwarding flags.
  const cliArgs = process.argv.slice(2).filter((a) => a !== "--");
  let urls;
  if (cliArgs.length > 0) {
    // Validate: each arg must start with https://<HOST>/
    const prefix = `https://${HOST}/`;
    const bad = cliArgs.filter((u) => !u.startsWith(prefix));
    if (bad.length) {
      console.error(`Refusing to submit URLs that don't start with ${prefix}:`);
      for (const u of bad) console.error(`  - ${u}`);
      console.error(`IndexNow rejects mixed hosts; cancelling.`);
      process.exit(1);
    }
    urls = cliArgs;
  } else {
    console.log(`Loading sitemap from ${SITEMAP_URL} …`);
    urls = await loadUrlsFromSitemap();
    console.log(`Loaded ${urls.length} URLs from sitemap.`);
  }
  await notify(urls);
}

main().catch((err) => {
  console.error(`✗ ${err.message}`);
  process.exit(3);
});
